-- 0003_login_attempts — журнал попыток входа. Он же основа ограничения частоты.
--
-- Зачем: bcrypt делает перебор медленным, но не невозможным. Один хеш — около
-- 0,3 с, значит с одной машины это ~3 пароля в секунду, а с сотни машин уже
-- триста. Словарь из миллиона популярных паролей при таком темпе проходится
-- меньше чем за час. Нужен предел, который не зависит от скорости атакующего.
--
-- Таблица заодно журнал: по ней видно, кого и откуда пытались подобрать. Это
-- не побочный эффект, а вторая причина хранить попытки строками, а не
-- счётчиком, — счётчик отвечает «сколько», журнал отвечает «кто и когда».

create table login_attempts (
  -- Здесь, в отличие от остальных таблиц, обычный счётчик, а не uuid.
  -- Причины выбрать uuid (id уходит наружу в адресах, строки склеиваются из
  -- разных источников) к журналу не относятся: он не покидает сервер. Зато
  -- строк тут на порядки больше, а bigint вдвое уже uuid и лучше ложится в
  -- индекс по времени.
  id bigint generated always as identity primary key,

  -- Адрес хранится как его ввели, а считается по lower(): иначе предел
  -- обходится чередованием регистра. Не ссылка на users намеренно — попытки
  -- под несуществующий адрес нужно считать точно так же (см. ниже).
  email text,
  ip    inet,

  successful boolean     not null,
  created_at timestamptz not null default now()
);

-- Оба индекса обслуживают один и тот же запрос «сколько неудач за последние N
-- минут» — по адресу и по адресу источника. Частичные: удачные попытки в
-- подсчёте предела не участвуют никогда.
create index login_attempts_email_idx on login_attempts (lower(email), created_at desc)
  where not successful;
create index login_attempts_ip_idx on login_attempts (ip, created_at desc)
  where not successful;

-- Для регулярной уборки: журнал растёт с каждой попыткой и без неё займёт
-- всю базу. Строки старше окна предела нужны только как история.
create index login_attempts_created_idx on login_attempts (created_at);

comment on table login_attempts is 'Попытки входа: предел частоты и журнал подозрительной активности.';
comment on column login_attempts.email is 'Адрес как его ввели. Может не соответствовать ни одному пользователю.';
