-- 0004_billing — то, чего не хватало для приёма платежей и учёта комиссии.
--
-- Здесь нет ни ключей, ни ставок: и то и другое живёт в переменных окружения.
-- Ставка комиссии, зашитая в схему, потребовала бы миграции при каждом её
-- пересмотре, а ключ в базе — это ключ, который уедет вместе с её копией.

-- ─────────────────────────────────────────────────────────────────────────
-- Подписки: то, чем банк опознаёт сохранённую карту
-- ─────────────────────────────────────────────────────────────────────────

-- RebillId выдаёт Т-Касса после первого успешного платежа. Он не является
-- номером карты и не позволяет ничего узнать о ней — по нему можно только
-- списать повторно через наш же терминал. Сами реквизиты карты к нам не
-- попадают никогда: их вводят на стороне банка.
alter table subscriptions add column rebill_id text;

comment on column subscriptions.rebill_id is
  'Идентификатор сохранённой карты в Т-Кассе для повторных списаний. Не реквизиты карты.';

-- ─────────────────────────────────────────────────────────────────────────
-- Комиссия: фиксированная часть рядом с процентной
-- ─────────────────────────────────────────────────────────────────────────

-- Вознаграждение состоит из двух слагаемых: фиксированного за сделку и доли
-- от суммы. Хранить только их сумму нельзя — через год никто не восстановит,
-- из чего она сложилась, а именно это спрашивают при разборе спорной сделки.
alter table transactions
  add column commission_fixed_amount numeric(14, 2) not null default 0;

alter table transactions
  add constraint transactions_fixed_fee_non_negative check (commission_fixed_amount >= 0),
  -- Фиксированная часть не может превышать всю комиссию: иначе процентная
  -- часть оказалась бы отрицательной, а это уже не комиссия, а скидка.
  add constraint transactions_fixed_fee_within_commission
    check (commission_fixed_amount <= commission_amount);

comment on column transactions.commission_fixed_amount is
  'Фиксированная часть вознаграждения. commission_amount = она + доля от gross_amount.';

-- ─────────────────────────────────────────────────────────────────────────
-- Платёж заводится раньше, чем подписка
-- ─────────────────────────────────────────────────────────────────────────

-- Прежнее правило требовало ссылку на подписку у любой строки вида
-- subscription_fee. Но порядок событий обратный: сначала мы заводим платёж и
-- отправляем человека на страницу банка, и только когда деньги дошли —
-- открываем оплаченный период. До этого ссылаться не на что.
--
-- Смысл правила сохраняется там, где он важен: у **состоявшегося** платежа
-- подписка обязана быть. Незавершённый платёж может её не иметь.
alter table transactions drop constraint transactions_fee_has_subscription;

alter table transactions add constraint transactions_fee_has_subscription check (
  kind <> 'subscription_fee' or status <> 'succeeded' or subscription_id is not null
);

