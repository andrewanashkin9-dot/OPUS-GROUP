-- 0008 — тип приветственного уведомления.
--
-- Приветствие живёт в той же таблице notifications, что и всё остальное:
-- отдельная табличка «показали ли мы человеку приветствие» — это та же
-- строка «кому, о чём, прочитано ли», только своя, со своим запросом и
-- своим способом рассинхронизироваться.
--
-- «Показано» — это read_at. Ровно то, что нужно: карточка ищет своё
-- приветствие непрочитанным, показывает его один раз и тем же движением
-- помечает прочитанным.

alter type notification_kind add value 'welcome';

comment on type notification_kind is 'Виды уведомлений. welcome — приветствие после регистрации, показывается один раз.';
