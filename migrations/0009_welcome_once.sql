-- 0009 — одно приветствие на человека.
--
-- Отдельным файлом от 0008 не по прихоти: PostgreSQL не позволяет
-- использовать новое значение enum в той же транзакции, в которой оно
-- добавлено, — а каждая миграция у нас выполняется одной транзакцией
-- (см. scripts/migrate.ts). Предикат этого индекса упоминает 'welcome',
-- поэтому он обязан приехать следующим файлом.
--
-- Зачем индекс, если приветствие создаётся один раз при регистрации: затем,
-- что «один раз» здесь — обещание кода, а обещания кода обходятся повторным
-- запуском сида, ручной вставкой и любым будущим «а давайте покажем
-- приветствие ещё и тем, кто регистрировался раньше». Два приветствия у
-- одного человека база теперь просто не примет.

create unique index notifications_welcome_once_idx
  on notifications (user_id)
  where kind = 'welcome';
