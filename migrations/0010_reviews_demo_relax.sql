-- ⚠️⚠️ 0010 — ВРЕМЕННОЕ ТЕСТОВОЕ ПОСЛАБЛЕНИЕ. ОТКАТИТЬ ПЕРЕД ЗАПУСКОМ. ⚠️⚠️
--
-- Что делает: снимает правило «отзыв только по своей завершённой заявке» и
-- разрешает отзыв любому вошедшему пользователю о любом исполнителе — чтобы
-- форму подачи отзыва можно было потрогать руками, не проходя каждый раз
-- весь путь заявка → отклик → принятие → завершение.
--
-- Взамен остаётся одно правило: **один отзыв от одного человека об одном
-- исполнителе.** Без него тестовые отзывы плодились бы бесконечно.
--
-- Чем это плохо по-настоящему, если забыть откатить: рейтинг перестаёт быть
-- свидетельством. Любой зарегистрировавшийся сможет поставить конкуренту
-- единицу, ни разу с ним не работав, — а по этому рейтингу заказчик выбирает,
-- кому доверить крышу. Это не «неубранная демка», это подрыв главного, за чем
-- сюда приходят.
--
-- ─────────────────────────────────────────────────────────────────────────
-- ОТКАТ. Выполнить целиком следующей миграцией (0011_reviews_strict.sql):
-- ─────────────────────────────────────────────────────────────────────────
--
--   -- сначала убрать отзывы, не привязанные к заявке: под строгим правилом
--   -- таких не бывает, и они не дадут вернуть not null
--   alter table reviews disable trigger reviews_forbid_rewrite_trg;
--   delete from reviews where request_id is null;
--   alter table reviews enable trigger reviews_forbid_rewrite_trg;
--
--   drop index reviews_demo_one_per_pair_idx;
--   drop index reviews_one_per_request_idx;
--   alter table reviews alter column request_id set not null;
--   alter table reviews add constraint reviews_one_per_request unique (request_id);
--   create trigger reviews_check_eligibility_trg before insert on reviews
--     for each row execute function reviews_check_eligibility();
--
-- Функция reviews_check_eligibility() специально НЕ удаляется — только
-- триггер. Удалить её значило бы переписывать правило заново по памяти,
-- а оно должно вернуться ровно тем же, каким было.

-- 1. Отзыв без заявки. Раньше это было невозможно по определению: отзыв —
--    свидетельство о конкретной работе. На время проверки — можно.
alter table reviews alter column request_id drop not null;

-- 2. «Один отзыв на заявку» остаётся, но только для отзывов, у которых
--    заявка есть. В PostgreSQL unique пропускает NULL как «разные значения»,
--    но частичный индекс говорит об этом вслух, а не полагается на то, что
--    читающий помнит это правило.
alter table reviews drop constraint reviews_one_per_request;
create unique index reviews_one_per_request_idx
  on reviews (request_id) where request_id is not null;

-- 3. Собственно послабление: проверка «своя завершённая заявка» снимается.
--    Снимается только триггер — сама функция остаётся в базе нетронутой,
--    чтобы откат вернул правило слово в слово.
drop trigger reviews_check_eligibility_trg on reviews;

-- 4. Взамен — один отзыв от человека об исполнителе.
--    ⚠️ Это НЕ то правило, которое должно остаться: настоящее — «один отзыв
--    на заявку», потому что один и тот же заказчик может нанимать бригаду
--    годами и каждая работа заслуживает своей оценки.
create unique index reviews_demo_one_per_pair_idx on reviews (author_id, executor_id);

comment on table reviews is
  '⚠️ ВРЕМЕННО ОСЛАБЛЕНО (миграция 0010): отзыв может оставить любой вошедший, один раз на исполнителя. Вернуть строгое правило перед запуском.';
