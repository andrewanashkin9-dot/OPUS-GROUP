-- 0014 — «прочитано» у сообщений заявки.
--
-- Дата, а не флаг «да/нет»: она отвечает и на вопрос «когда», который
-- всплывает в разборе «я вам писал ещё во вторник». Так же устроено
-- read_at у уведомлений — одно понятие, одна форма записи.
--
-- Колонка появилась отдельной миграцией, а не в 0011, потому что чат уже
-- работает на боевой схеме: 0011 применена и правке не подлежит.

alter table request_messages add column read_at timestamptz;

-- Счётчик непрочитанного у собеседника. Частичный индекс: прочитанные в нём
-- не лежат вовсе, поэтому он остаётся крошечным даже когда переписка
-- разрослась до сотен строк.
create index request_messages_unread_idx
  on request_messages (request_id, author_id)
  where read_at is null;

comment on column request_messages.read_at is
  'Когда собеседник прочитал. NULL — ещё не прочитано. Своё сообщение автору не помечается: он его и так видел.';
