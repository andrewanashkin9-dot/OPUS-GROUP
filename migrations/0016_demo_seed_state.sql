-- 0016 — отметка о том, что демо-данные уже заводились.
--
-- ⚠️ Часть временной демонстрации (см. TODO_BEFORE_LAUNCH.md), но таблица
-- маленькая и безобидная: удалять её вместе с остальным необязательно.
--
-- Зачем она. Демо-данные заводятся автоматически при боевом деплое, и
-- «автоматически» здесь обязано означать «ровно один раз». Проверять по
-- наличию самих данных нельзя: когда перед запуском их уберут
-- (`demo:seed -- --clean`), следующий же деплой завёл бы их заново — и
-- выдуманные бригады появились бы на живом сайте.
--
-- Поэтому решение принимается по отметке, а не по данным. Отметка
-- переживает уборку: убрали демо-данные — они больше не вернутся сами.
-- Понадобятся снова — заводятся руками, `npm run demo:seed`.

create table demo_seed_state (
  -- Строка ровно одна. Ключ-константа, а не последовательность: у «когда мы
  -- заводили демо-данные» не бывает второго ответа, и таблица, которая
  -- умеет копить строки, рано или поздно их накопит.
  id boolean not null primary key default true,

  seeded_at timestamptz not null default now(),

  -- Чем заведено: деплоем или руками. Пригодится ровно один раз — когда
  -- кто-то спросит «откуда на сайте Аркадий Пестов».
  source text not null,

  constraint demo_seed_state_single_row check (id = true)
);

comment on table demo_seed_state is
  '⚠️ Временное. Отметка «демо-данные уже заводились», чтобы деплой не заводил их повторно и не возвращал после уборки.';
