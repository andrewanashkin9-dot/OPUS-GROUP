/**
 * Миграции при деплое.
 *
 *     npm run db:migrate:deploy
 *
 * Вызывается из `vercel-build` перед сборкой. Отдельный файл, а не флаг у
 * обычного `db:migrate`, потому что у него другая работа: обычный запускают
 * руками и хотят, чтобы он ругался, если что-то не так; этот запускается сам
 * на каждый деплой, и половина его смысла — вовремя **не** запуститься.
 *
 * Три причины пропустить, и все три — не ошибка:
 *
 *  1. **Переменные базы не заданы.** Так собирается витрина без базы, и так
 *     же соберётся форк или превью, куда секреты не проброшены. Валить
 *     сборку из-за этого нельзя: сайт без базы работает, просто без заявок.
 *
 *  2. **Это не боевой деплой.** Превью-сборка каждой ветки применила бы к
 *     боевой базе миграции из ветки, которую ещё никто не смотрел. Схема
 *     поехала бы вперёд кода, и откатывать это пришлось бы руками. Боевой
 *     деплой узнаётся по VERCEL_ENV=production.
 *
 *  3. **Применять нечего.** Обычное состояние: код меняется чаще схемы.
 *
 * А вот упавшая миграция сборку **валит**, и это правильно: выкатить код,
 * который ждёт колонки, которой нет, — это пятисотые у живых людей вместо
 * красной сборки, которую видит один человек.
 */
import { spawn } from "node:child_process";
import { loadEnvConfig } from "@next/env";

loadEnvConfig(process.cwd());

/**
 * Где мы собираемся. `production` — боевой деплой, `preview` — ветка,
 * `development` — `vercel dev`. Вне Vercel переменной нет вовсе.
 */
const vercelEnv = process.env.VERCEL_ENV;

/**
 * Аварийный выключатель.
 *
 * Понадобится в одном случае: миграция ломает сборку, а выкатить нужно
 * прямо сейчас. Тогда переменная ставится в панели Vercel, деплой проходит
 * без миграций, а схема догоняется руками. Без такого выключателя
 * единственным способом остаётся правка build command в чужой панели под
 * давлением — худший момент для правки чего бы то ни было.
 */
const skipRequested = ["1", "true", "yes"].includes(
  (process.env.SKIP_DEPLOY_MIGRATIONS ?? "").toLowerCase(),
);

async function main(): Promise<void> {
  if (skipRequested) {
    console.log("SKIP_DEPLOY_MIGRATIONS — миграции пропущены по требованию.");
    return;
  }

  // Проверка окружения до импорта модулей базы: они читают переменные при
  // загрузке и без них бросают исключение.
  const { isDbConfigured, describeDbTarget, getDbConfig } = await import(
    "../src/lib/server/db-config"
  );

  if (!isDbConfigured()) {
    console.log("Переменные PostgreSQL не заданы — миграции пропущены, сборка продолжается.");
    return;
  }

  // Вне Vercel (локально, в CI) переменной нет, и это не повод пропускать:
  // запустили руками — значит хотели.
  if (vercelEnv && vercelEnv !== "production") {
    console.log(
      `Деплой окружения «${vercelEnv}», а не production — миграции пропущены.\n` +
        "Схему меняет только боевой деплой: иначе превью ветки применило бы\n" +
        "к боевой базе то, что ещё никто не смотрел.",
    );
    return;
  }

  console.log(`Миграции перед сборкой. База: ${describeDbTarget(getDbConfig())}`);

  // Обычный `db:migrate` запускается отдельным процессом, а не импортом.
  //
  // Импорт выполнил бы его main() как побочный эффект загрузки модуля —
  // ровно то, чего от импорта не ждут. Отдельный процесс к тому же честно
  // отдаёт код возврата: упала миграция — упала сборка, без пересказа
  // ошибки своими словами.
  await run("npx", ["tsx", "--conditions=react-server", "scripts/migrate.ts"]);
}

function run(command: string, args: string[]): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { stdio: "inherit", env: process.env });
    child.on("error", reject);
    child.on("close", (code) => {
      if (code === 0) resolve();
      else reject(new Error(`${command} завершился с кодом ${code}`));
    });
  });
}

main().catch((error: unknown) => {
  console.error(`\n❌ Миграции не применились: ${error instanceof Error ? error.message : String(error)}`);
  console.error(
    "\nСборка остановлена намеренно: код, который ждёт новой схемы, не должен\n" +
      "попасть на боевой сайт раньше самой схемы.\n" +
      "Выкатить без миграций (и догнать схему руками) — переменная\n" +
      "SKIP_DEPLOY_MIGRATIONS=1 в настройках проекта Vercel.",
  );
  process.exitCode = 1;
});
