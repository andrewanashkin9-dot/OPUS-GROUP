"use client";

import { useEffect } from "react";
import type { Locale } from "@/lib/i18n/locale";

/**
 * Проставляет `lang` на <html> для переведённых страниц.
 *
 * Атрибут стоит в корневой разметке, а она одна на весь сайт и собирается
 * заранее — узнать из неё адрес нельзя, не сделав динамическими вообще все
 * страницы. Цена оказалась несоразмерной: `lang` нужен программе чтения с
 * экрана, чтобы выбрать произношение, и поисковику — и обоим достаточно
 * значения, выставленного при загрузке.
 *
 * Поэтому здесь маленький клиентский компонент вместо перестройки всего
 * дерева. Разметка от него не зависит: он ничего не рисует и меняет один
 * атрибут уже существующего элемента.
 */
export function LocaleHtmlLang({ locale }: { locale: Locale }) {
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  return null;
}
