"use client";

import { useEffect } from "react";
import { useRouter } from "next/navigation";
import { useRoleCookie } from "@/lib/auth/useRoleCookie";

/**
 * TODO: удалить перед запуском — автоматический вход гостем.
 *
 * Ничего не рисует. Единственная задача: если посетитель пришёл без сессии,
 * тихо попросить её у /api/demo/guest — и тогда всё остальное на сайте
 * работает без регистрации, как обычные страницы.
 *
 * Почему это делает браузер, а не proxy.ts, который и так видит каждый
 * запрос: proxy выполняется перед отдачей любой страницы, включая главную и
 * магазин, которые собраны заранее и лежат на CDN. Ходить оттуда в базу —
 * значит превратить готовые страницы в вычисляемые на каждый заход. Здесь же
 * запрос уходит один раз, уже после того как страница показана.
 *
 * Один раз за жизнь вкладки — за это отвечает `attempted` рядом с модулем, а
 * не состояние компонента: React в строгом режиме монтирует дерево дважды, и
 * без него первый заход заводил бы двух гостей вместо одного.
 */

/** Заходили ли уже за гостем в этой вкладке. */
let attempted = false;

export function DemoAutoGuest() {
  const role = useRoleCookie();
  const router = useRouter();

  useEffect(() => {
    if (role !== null || attempted) return;
    attempted = true;

    void (async () => {
      try {
        const response = await fetch("/api/demo/guest", { method: "POST" });
        if (!response.ok) return;
        // refresh, а не reload: страницы серверные, и Next перерисует их с
        // новой сессией, не перезагружая приложение целиком. Заодно это
        // перечитывает cookie роли, от которой зависят плашка в углу, форма
        // отзыва и кнопка «Написать менеджеру».
        router.refresh();
      } catch {
        // Сеть отвалилась или базы нет — сайт остаётся таким, каким был без
        // этой вставки. Гостю незачем показывать ошибку того, чего он не
        // просил.
      }
    })();
  }, [role, router]);

  return null;
}
