export function educationCardForKind(kind: EducationCard["nodeKind"], materialId?: string) {
  const candidates = EDUCATION_CARDS.filter((c) => c.nodeKind === kind);
  if (candidates.length === 0) return undefined;
  if (!materialId) return candidates[0];
  const hash = Array.from(materialId).reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
  return candidates[hash % candidates.length];
}
