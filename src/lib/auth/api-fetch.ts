/**
 * Запросы к своему API с автоматическим продлением сессии.
 *
 * Access-токен живёт 15 минут. Без этого перехватчика человек, оставивший
 * вкладку открытой на обед, возвращается к приложению, которое на всё
 * отвечает «требуется вход», — хотя его сессия жива ещё 30 дней.
 *
 * Схема простая: получили 401 — сходили на /api/auth/refresh — повторили
 * исходный запрос. Один раз. Если и после продления 401, значит сессия
 * действительно кончилась (вышли, заблокировали, истекли 30 дней), и надо
 * идти на форму входа.
 *
 * Почему не подменяем глобальный `fetch`. Так «перехват» получился бы
 * незаметным и всеобщим: под него попали бы запросы самого Next (навигация,
 * подгрузка кусков страницы) и любых сторонних библиотек. Отлаживать
 * чужой запрос, который кто-то по дороге переписал, — отдельный род мучений.
 * Явная функция ограничивает поведение нашими же маршрутами.
 */

/**
 * Общее обещание на время продления.
 *
 * Нужно, потому что 401 обычно приходит не один: страница шлёт три-четыре
 * запроса разом, и все они получают 401 одновременно. Без этой переменной
 * каждый пошёл бы продлевать сессию сам, и они бы передрались — refresh-токен
 * при продлении заменяется на новый, поэтому второе продление пришло бы уже
 * со старым, отозванным токеном и выкинуло бы человека из аккаунта.
 *
 * С ней первый запускает продление, остальные ждут его результата.
 */
let refreshInFlight: Promise<boolean> | null = null;

function refreshSession(): Promise<boolean> {
  refreshInFlight ??= fetch("/api/auth/refresh", {
    method: "POST",
    // Явно: нам нужны cookie, и ответ не должен браться из кеша.
    credentials: "same-origin",
    cache: "no-store",
  })
    .then((response) => response.ok)
    .catch(() => false)
    .finally(() => {
      // Обнуляем, иначе следующий 401 через час получит результат
      // позапрошлого продления.
      refreshInFlight = null;
    });

  return refreshInFlight;
}

export interface ApiResult<T> {
  ok: boolean;
  status: number;
  data: T;
  /**
   * Сессия кончилась насовсем: продлить не удалось. Отдельный признак, а не
   * просто `status === 401`, потому что для вызывающего это разные вещи —
   * «нет прав на это действие» и «пора на форму входа».
   */
  authExpired: boolean;
}

/**
 * Запрос с одной попыткой продления.
 *
 * Сам никуда не уводит: перенаправление — дело того, кто знает про
 * маршрутизацию (см. useApiFetch). Модуль, который дёргает
 * window.location из недр сетевого слоя, ломает навигацию Next и не
 * поддаётся тестированию.
 */
export async function apiFetch(input: string, init: RequestInit = {}): Promise<Response> {
  const request = () =>
    fetch(input, { credentials: "same-origin", cache: "no-store", ...init });

  const first = await request();
  if (first.status !== 401) return first;

  // Сами маршруты авторизации не перехватываем: 401 от /login означает
  // «неверный пароль», и продлевать там нечего. Попытка привела бы к
  // лишнему запросу на каждый неверный ввод пароля.
  if (input.startsWith("/api/auth/")) return first;

  const refreshed = await refreshSession();
  if (!refreshed) return first;

  // Повтор ровно один. Если и он вернёт 401 — значит дело не в сроке токена
  // (мы только что его обновили), и второй заход ничего не изменит, а вот
  // бесконечный цикл запросов устроит.
  return request();
}

/** Тот же запрос, но сразу разобранный JSON и с признаком истёкшей сессии. */
export async function apiJson<T>(input: string, init?: RequestInit): Promise<ApiResult<T>> {
  const response = await apiFetch(input, init);
  const data = (await response.json().catch(() => ({}))) as T;
  return {
    ok: response.ok,
    status: response.status,
    data,
    authExpired: response.status === 401 && !input.startsWith("/api/auth/"),
  };
}
