/**
 * ⚠️ ВРЕМЕННАЯ ДЕМО-ВСТАВКА — удаляется одним коммитом.
 *
 * Один выключатель на все временные штуки, добавленные, чтобы функции можно
 * было посмотреть глазами до того, как появятся настоящие данные:
 *
 *   1. сид-скрипт с тестовыми отзывами   — scripts/seed-demo.ts
 *   2. переключатель роли модератора     — src/app/api/demo/role/route.ts
 *                                          src/components/demo/DemoRoleSwitch.tsx
 *
 * Как убрать всё разом — см. README, раздел «Временные демо-вставки».
 *
 * По умолчанию выключено. Это важнее, чем кажется: пункт 2 позволяет любому
 * вошедшему сделать себя модератором, и забытый в боевом окружении флаг —
 * это не «неубранная демка», а дыра в правах.
 *
 * Здесь нет `import "server-only"`: значение читается и на сервере (маршрут),
 * и при сборке страницы, которая передаёт его в браузер.
 */
export function isDemoMode(): boolean {
  const raw = (process.env.DEMO_MODE ?? "").toLowerCase();
  return raw === "true" || raw === "1" || raw === "yes";
}
