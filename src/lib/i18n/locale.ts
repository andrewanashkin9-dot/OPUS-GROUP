/**
 * Два языка сайта и правила адресов.
 *
 * Английская версия живёт на отдельных адресах с префиксом `/en`, а не
 * подставляется по cookie на тех же самых. Три причины, и все три
 * практические:
 *
 *  1. **Страницы остаются заранее собранными.** Главная и каталог отдаются с
 *     CDN готовыми; страница, которая читает cookie, чтобы выбрать язык,
 *     обязана собираться на каждый запрос. Это самое дорогое, что есть у
 *     сайта, и менять его на удобство переключателя нельзя.
 *  2. **Английскую версию можно найти.** У `/en` есть свой адрес: его
 *     индексирует поиск, им делятся ссылкой, он открывается тем же, чем был
 *     закрыт. Язык, спрятанный в cookie, существует только для того, кто уже
 *     на сайте и уже нажал.
 *  3. **Русские адреса не сломались.** Все существующие ссылки, из писем и
 *     из поиска, ведут туда же, куда вели.
 *
 * Цена решения — каждая переведённая страница существует дважды в дереве
 * маршрутов. Содержимое при этом одно: обе ветки рисуют один компонент,
 * отличается только переданный язык.
 */

export const LOCALES = ["ru", "en"] as const;
export type Locale = (typeof LOCALES)[number];

export const DEFAULT_LOCALE: Locale = "ru";

/** Человеческие имена — для переключателя и атрибута lang. */
export const LOCALE_LABELS: Record<Locale, string> = { ru: "RU", en: "EN" };

/**
 * Адрес внутри выбранного языка.
 *
 * `localePath("en", "/services")` → `/en/services`
 * `localePath("ru", "/services")` → `/services`
 *
 * Якоря и внешние ссылки проходят насквозь: `mailto:`, `tel:` и `#pricing`
 * префикса не получают — иначе почтовая ссылка превратилась бы в
 * несуществующую страницу.
 */
export function localePath(locale: Locale, href: string): string {
  if (locale === DEFAULT_LOCALE) return href;
  if (!href.startsWith("/")) return href;
  if (href === "/") return "/en";
  return `/en${href}`;
}

/**
 * Тот же адрес на другом языке — для переключателя.
 *
 * Переключатель обязан оставлять человека там, где он стоял: увести его с
 * карточки товара на главную только потому, что он сменил язык, — это
 * потерять то, что он читал.
 *
 * Страницы, у которой нет перевода, это не касается: сюда приходит текущий
 * путь, и если английской версии нет, переключателя на ней тоже нет
 * (см. TRANSLATED_PAGES).
 */
export function switchLocalePath(pathname: string, to: Locale): string {
  const bare = pathname === "/en" ? "/" : pathname.startsWith("/en/") ? pathname.slice(3) : pathname;
  return localePath(to, bare);
}

/**
 * Какие страницы переведены.
 *
 * Список, а не догадка по наличию файла: переключатель не должен вести на
 * `/en/cabinet`, которого нет. Пока переведены публичные страницы — главная
 * (вместе с тарифами, они её раздел) и бригады; формы и кабинет остаются
 * русскими, и на них переключателя нет вовсе.
 *
 * Показать переключатель там, где перевода нет, значит пообещать язык,
 * которого не будет, — и человек нажмёт, получит 404 и решит, что сломан
 * сайт целиком.
 */
export const TRANSLATED_PAGES = ["/", "/services", "/market"] as const;

/**
 * Страницы товаров тоже переведены, но их 37 и перечислять их незачем:
 * достаточно правила «всё внутри /market».
 */
export function isTranslated(pathname: string): boolean {
  const bare = pathname === "/en" ? "/" : pathname.startsWith("/en/") ? pathname.slice(3) : pathname;
  if (bare.startsWith("/market/")) return true;
  return (TRANSLATED_PAGES as readonly string[]).includes(bare);
}

/** Язык по адресу — для страниц, которые его не получают пропсом. */
export function localeFromPath(pathname: string): Locale {
  return pathname === "/en" || pathname.startsWith("/en/") ? "en" : "ru";
}
