/**
 * ВРЕМЕННО — удаляется вместе со страницей `/diag-7f4a2c91`.
 *
 * Форма одного ответа вендора, показываемая на странице-пробе.
 *
 * Живёт отдельно от `server/neural4d-probe.ts` по одной причине: тот помечен
 * `server-only`, а эту форму нужно знать и клиентскому компоненту, который
 * её рисует. Здесь нет ни ключа, ни адресов — только описание полей.
 */
export interface ProbeResult {
  /** Полный адрес, по которому ушёл запрос. Секретов в нём нет. */
  url: string;
  /** Зачем этот адрес в списке — читается вместе с ответом. */
  note: string;
  /** null, если до ответа дело не дошло (DNS, TLS, таймаут). */
  status: number | null;
  statusText: string;
  /** Начало тела ответа либо текст сетевой ошибки. */
  body: string;
  /** Тип содержимого — по нему видно, HTML это от прокси или JSON вендора. */
  contentType: string;
}
