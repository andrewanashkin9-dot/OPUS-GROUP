import "server-only";

import bcrypt from "bcryptjs";

/**
 * Хеширование паролей.
 *
 * Пароль не хранится и не может быть восстановлен — хранится bcrypt-хеш.
 * При входе сравниваются хеши, а не пароли: даже с полной копией базы
 * войти под чужим именем нельзя.
 *
 * Почему bcrypt, а не SHA-256: обычные хеш-функции создавались быстрыми.
 * Видеокарта считает миллиарды SHA-256 в секунду, и словарь из миллиона
 * популярных паролей проверяется за доли секунды. bcrypt нарочно медленный
 * и с настраиваемой «стоимостью»: один хеш занимает сотни миллисекунд, и
 * тот же перебор растягивается на годы.
 */

/**
 * Стоимость. Каждая единица удваивает время: 12 — примерно 0,3 с на хеш.
 *
 * Это верхняя граница того, что человек не замечает при входе, и нижняя
 * того, что делает перебор бессмысленным. Поднимать имеет смысл вместе с
 * ростом мощности серверов; старые хеши при этом продолжают работать —
 * стоимость записана внутри самого хеша.
 */
const COST = 12;

/** Ниже этой длины пароль не принимается: короткие подбираются словарём. */
export const MIN_PASSWORD_LENGTH = 8;

/**
 * bcrypt учитывает только первые 72 байта. Молча обрезать нельзя: человек
 * с длинной парольной фразой был бы уверен в защите, которой нет.
 */
export const MAX_PASSWORD_BYTES = 72;

export function validatePassword(password: string): string | null {
  if (password.length < MIN_PASSWORD_LENGTH) {
    return `Пароль должен быть не короче ${MIN_PASSWORD_LENGTH} символов`;
  }
  if (Buffer.byteLength(password, "utf8") > MAX_PASSWORD_BYTES) {
    return `Пароль длиннее ${MAX_PASSWORD_BYTES} байт не поддерживается`;
  }
  return null;
}

export function hashPassword(password: string): Promise<string> {
  return bcrypt.hash(password, COST);
}

/**
 * Проверка пароля.
 *
 * `hash` может быть null — у пользователя может не быть пароля (вход по
 * телефону, будущий вход через соцсеть). Такой случай обязан занимать
 * столько же времени, сколько обычная проверка: иначе по скорости ответа
 * можно перебором узнать, какие адреса зарегистрированы. Поэтому вместо
 * быстрого `return false` считается хеш заведомо неверного пароля.
 */
export async function verifyPassword(password: string, hash: string | null): Promise<boolean> {
  if (!hash) {
    await bcrypt.compare(password, DUMMY_HASH);
    return false;
  }
  return bcrypt.compare(password, hash);
}

// Хеш случайной строки, посчитанный один раз при старте. Нужен только чтобы
// «пустая» проверка занимала столько же времени, сколько настоящая.
const DUMMY_HASH = bcrypt.hashSync("nobody-will-ever-use-this-password", COST);
