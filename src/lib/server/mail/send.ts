import "server-only";

/**
 * Отправка писем.
 *
 * Почтовый сервис к проекту пока не подключён — это отдельное решение с
 * договором и настройкой домена. Поэтому здесь **сменный** отправитель:
 * пока адрес SMTP не задан, письмо печатается в лог сервера вместе со
 * ссылкой.
 *
 * Это не заглушка «чтобы собиралось»: в таком виде и подтверждение почты, и
 * восстановление пароля работают полностью — ссылку видно в логе и по ней
 * можно пройти. Когда появится почтовый сервис, поменяется одна функция,
 * а всё остальное останется как есть.
 *
 * Чего здесь намеренно нет: писем в HTML, вложений, шаблонов. Письмо со
 * ссылкой на смену пароля должно доходить, а не выглядеть — красивый HTML
 * чаще попадает в спам, чем простой текст.
 */

export interface Letter {
  to: string;
  subject: string;
  text: string;
}

function isConfigured(): boolean {
  return Boolean(process.env.SMTP_URL?.trim());
}

/**
 * Отправляет письмо.
 *
 * Возвращает признак «ушло по-настоящему», чтобы вызывающий код мог сказать
 * человеку правду, а не бодрое «письмо отправлено» в пустоту.
 */
export async function sendLetter(letter: Letter): Promise<{ delivered: boolean }> {
  if (!isConfigured()) {
    // Адрес получателя в лог не пишем целиком: лог читают больше людей, чем
    // почтовый ящик, а адрес — персональные данные.
    console.log(
      `\n──── ПИСЬМО (почтовый сервис не подключён) ────\n` +
        `кому:  ${maskEmail(letter.to)}\n` +
        `тема:  ${letter.subject}\n\n${letter.text}\n` +
        `───────────────────────────────────────────────\n`,
    );
    return { delivered: false };
  }

  // Здесь появится вызов настоящего отправителя. Специально не пишу его
  // «на будущее»: непроверенный код отправки писем создаёт ложную
  // уверенность, что почта работает.
  throw new Error(
    "SMTP_URL задан, но отправитель не реализован — подключите почтовый сервис в src/lib/server/mail/send.ts",
  );
}

/** i***@example.com — достаточно, чтобы узнать свой адрес, и мало для чужого. */
function maskEmail(email: string): string {
  const [name, domain] = email.split("@");
  if (!domain) return "***";
  return `${name.slice(0, 1)}***@${domain}`;
}
