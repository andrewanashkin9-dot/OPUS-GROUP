import "server-only";

/**
 * Слой вендоров 3D-реконструкции.
 *
 * Вендор живёт на сервере, а не в браузере, по двум причинам:
 *  - у него есть ключ, и ключ не должен покидать сервер;
 *  - выбор вендора определяет, чей счёт оплачивается. Если бы выбор делал
 *    клиент, любой посетитель мог бы переключить генерацию на другого
 *    вендора — то есть на другой ваш счёт.
 *
 * Поэтому браузер знает ровно один адрес — наш собственный маршрут, а какой
 * вендор за ним стоит, решает переменная ACTIVE_3D_PROVIDER.
 */

export type VendorId = "neural4d" | "genapi";

export const VENDOR_IDS: VendorId[] = ["neural4d", "genapi"];

/**
 * Вендорная часть работы: единственное, что действительно требует обращения
 * наружу — построение модели по фотографиям.
 *
 * Остальные методы Model3DProvider (смена материала, этажность, расчёт сметы)
 * сюда намеренно не входят: это операции над уже полученной моделью, они
 * выполняются локально и одинаковы для любого вендора. Заставлять адаптер
 * вендора реализовывать getBillOfMaterials значило бы дублировать расчёт
 * сметы в каждом вендоре и однажды получить разные цены у разных вендоров.
 */
export interface Model3DVendor {
  readonly id: VendorId;
  /** Человеку понятное имя — для сообщений и логов. */
  readonly label: string;
  /** Задан ли ключ. Без него вендор не вызывается. */
  isConfigured(): boolean;
  /**
   * Отправляет фотографии вендору и возвращает его ответ как есть.
   * Приведение к SceneModel и проверка — уже за пределами адаптера, чтобы
   * правила были общими для всех вендоров.
   */
  requestReconstruction(photos: File[], signal: AbortSignal): Promise<VendorResponse>;
}

export type VendorResponse =
  | { ok: true; payload: unknown }
  | { ok: false; status: number; kind: "http" | "not_json" };
