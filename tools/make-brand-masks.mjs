/**
 * Готовит фирменные знаки к работе на сайте.
 *
 *     npm i -D sharp
 *     node tools/make-brand-masks.mjs <папка-с-исходниками>
 *
 * Исходники приходят светлой графикой на тёмном фоне и **без прозрачности** —
 * то есть фон в них нарисован, а не отсутствует. Положить такой файл на
 * страницу нельзя: он принесёт с собой чёрный прямоугольник.
 *
 * Скрипт превращает яркость исходника в альфа-канал и выбрасывает цвет.
 * Получается маска: цвет ей задаёт CSS через currentColor, поэтому один файл
 * работает и на синей бумаге, и на чёрной, и золотым в подвале — без второго
 * файла и без ручного переключения.
 *
 * Лежит в репозитории, чтобы знаки можно было пересобрать из новых исходников,
 * а не подбирать пороги заново по памяти. Сами исходники сюда не кладутся:
 * они весят мегабайты, а всё в public/ раздаётся в интернет.
 */

import sharp from "sharp";

import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
/** Откуда брать исходники: аргументом, иначе — папка знаков в проекте. */
const SRC = path.join(process.argv[2] ?? path.join(ROOT, "public/assets/brand"), "/");
/** Куда класть готовые маски — всегда в проект. */
const OUT = path.join(ROOT, "public/assets/brand", "/");

/**
 * Превращает светлую графику на тёмном фоне в маску с настоящей прозрачностью.
 *
 * Смысл: яркость исходника становится альфа-каналом, а сам цвет выбрасывается.
 * Тогда один файл работает и на тёмной теме, и на светлой — цвет ему задаёт
 * CSS через currentColor, как уже сделано для прежнего знака.
 *
 * `lo` отсекает фон (фактуру бумаги, артефакты JPEG), `hi` возвращает чернилам
 * полную плотность: тонкие линии в исходнике никогда не бывают чисто белыми,
 * и без этого они читались бы серой мутью.
 */
async function toMask(file, { lo, hi, width, out, box = 8 }) {
  const grey = sharp(SRC + file).greyscale();
  const { data, info } = await grey.raw().toBuffer({ resolveWithObject: true });

  const alpha = Buffer.alloc(data.length);
  for (let i = 0; i < data.length; i++) {
    const v = (data[i] - lo) / (hi - lo);
    alpha[i] = v <= 0 ? 0 : v >= 1 ? 255 : Math.round(v * 255);
  }

  // Белый холст: важна только альфа, цвет всё равно заменит currentColor.
  const white = Buffer.alloc(data.length * 3, 255);
  const rgba = Buffer.alloc(data.length * 4);
  for (let i = 0; i < data.length; i++) {
    rgba[i * 4] = white[i * 3];
    rgba[i * 4 + 1] = white[i * 3 + 1];
    rgba[i * 4 + 2] = white[i * 3 + 2];
    rgba[i * 4 + 3] = alpha[i];
  }

  // Границы считаем сами, а не через .trim(): тот сравнивает цвет с углом
  // кадра и на почти-прозрачных краях останавливается слишком рано — у
  // надписи оставалось пустое поле в половину высоты, и в вёрстке оно
  // превратилось бы в необъяснимый отступ.
  //
  // Порог рамки задаётся отдельно от порога чернил: по краям кадра попадаются
  // одиночные светлые крапины (сор в фактуре бумаги, артефакты JPEG), и по
  // низкому порогу рамка растягивалась на весь кадр из-за пары точек.
  let x0 = info.width, y0 = info.height, x1 = -1, y1 = -1;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      if (alpha[y * info.width + x] > box) {
        if (x < x0) x0 = x;
        if (x > x1) x1 = x;
        if (y < y0) y0 = y;
        if (y > y1) y1 = y;
      }
    }
  }

  const result = await sharp(rgba, {
    raw: { width: info.width, height: info.height, channels: 4 },
  })
    .extract({ left: x0, top: y0, width: x1 - x0 + 1, height: y1 - y0 + 1 })
    .resize({ width, withoutEnlargement: true })
    // Палитра, а не полный цвет: в маске цвет один — белый, — и меняется
    // только прозрачность, так что 128 градаций альфы хватает с запасом,
    // а файл выходит вдвое легче.
    .png({ compressionLevel: 9, palette: true, colours: 128 })
    .toFile(OUT + out);

  console.log(`${out.padEnd(22)} ${result.width}x${result.height}  ${(result.size / 1024).toFixed(0)} КБ`);
}

// Надпись: буквы лежат около 230, всё между 32 и 224 — сор фактуры (0,3% от
// кадра). Режем высоко: буквы крупные и сплошные, сдвиг края в полпикселя на
// них незаметен, а крапины исчезают полностью.
await toMask("opus-wordmark.png.png", { lo: 140, hi: 230, width: 1400, out: "opus-wordmark.png", box: 96 });

// Контейнер: фон почти чёрный, но линии тонкие и сглаженные — порог ниже,
// иначе вместе с фоном срежется и сама графика.
// Контейнер в подвале около 120 px по высоте, поэтому 400 px по ширине
// покрывают даже тройную плотность экрана. Больше брать незачем: сглаженные
// волосяные линии дают много уникальных значений альфы и жмутся плохо —
// 600 px весили бы 133 КБ против нынешних 69.
await toMask("opus-container.png.jpeg", { lo: 14, hi: 200, width: 400, out: "opus-container.png", box: 40 });
